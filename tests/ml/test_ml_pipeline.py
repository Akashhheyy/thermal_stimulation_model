def test_saved_model_can_be_loaded_and_predict(tmp_path, ml_frame):
    features = prepare_features(ml_frame)
    y = ml_frame["mean_indoor_temperature_c"].astype(float)
    split = grouped_design_split(ml_frame, seed=42)
    fitted = train_models(
        lambda: build_models(seed=42, fast=True),
        features,
        {"mean_indoor_temperature_c": y},
        split.train_index,
        model_names=("random_forest",),
    )
    save_model(
        fitted[("mean_indoor_temperature_c", "random_forest")],
        tmp_path / "models",
        "mean_indoor_temperature_c",
        "random_forest",
    )
    loaded = load_trained_models(tmp_path / "models")
    assert ("mean_indoor_temperature_c", "random_forest") in loaded
    original = fitted[("mean_indoor_temperature_c", "random_forest")].predict(features)
    reloaded = loaded[("mean_indoor_temperature_c", "random_forest")].predict(features)
    np.testing.assert_allclose(original, reloaded)


def test_feature_ordering_consistent_between_train_and_predict(ml_frame):
    features = prepare_features(ml_frame)
    row = features.iloc[[0]]
    row_dict = {column: row[column].iloc[0] for column in FEATURE_COLUMNS}
    rebuilt = build_feature_row(row_dict, {})
    assert list(rebuilt.columns) == list(FEATURE_COLUMNS)
    # A trained model accepts the rebuilt single-row frame too.
    y = ml_frame["mean_indoor_temperature_c"].astype(float)
    split = grouped_design_split(ml_frame, seed=42)
    fitted = train_models(
        lambda: build_models(seed=42, fast=True),
        features,
        {"mean_indoor_temperature_c": y},
        split.train_index,
        model_names=("linear_regression",),
    )
    prediction = fitted[("mean_indoor_temperature_c", "linear_regression")].predict(rebuilt)
    assert prediction.shape == (1,)
    assert np.isfinite(prediction).all()