def test_feature_preparation_is_deterministic(ml_frame):
    first = prepare_features(ml_frame)
    second = prepare_features(ml_frame)
    pd.testing.assert_frame_equal(first, second)
    assert list(first.columns) == list(FEATURE_COLUMNS)


def test_categorical_encoding_works(ml_frame):
    features = prepare_features(ml_frame)
    pipeline = build_models(seed=42, fast=True)["linear_regression"]
    y = ml_frame["mean_indoor_temperature_c"].astype(float)
    pipeline.fit(features, y)
    names = pipeline.named_steps["preprocessing"].get_feature_names_out()
    joined = " ".join(names)
    assert "wall_material_brick_masonry" in joined
    assert "window_wall_orientation" in joined


def test_grouped_split_prevents_design_leakage(ml_frame):
    split = grouped_design_split(ml_frame, seed=42)
    train_designs = set(ml_frame.iloc[split.train_index]["design_id"])
    valid_designs = set(ml_frame.iloc[split.validation_index]["design_id"])
    test_designs = set(ml_frame.iloc[split.test_index]["design_id"])
    assert not (train_designs & valid_designs)
    assert not (train_designs & test_designs)
    assert not (valid_designs & test_designs)
    assert len(test_designs) >= 1


def test_same_seed_produces_identical_splits(ml_frame):
    first = grouped_design_split(ml_frame, seed=7)
    second = grouped_design_split(ml_frame, seed=7)
    assert np.array_equal(first.train_index, second.train_index)
    assert np.array_equal(first.validation_index, second.validation_index)
    assert np.array_equal(first.test_index, second.test_index)


def test_models_train_successfully(ml_frame):
    features = prepare_features(ml_frame)
    y = ml_frame["mean_indoor_temperature_c"].astype(float)
    split = grouped_design_split(ml_frame, seed=42)
    fitted = train_models(
        lambda: build_models(seed=42, fast=True),
        features,
        {"mean_indoor_temperature_c": y},
        split.train_index,
        model_names=("linear_regression", "random_forest"),
    )
    assert set(fitted) == {
        ("mean_indoor_temperature_c", "linear_regression"),
        ("mean_indoor_temperature_c", "random_forest"),
    }


