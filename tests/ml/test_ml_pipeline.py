# Synthetic test weather months for the fake transport.
_MONTH_BASE = {1: -10.0, 2: -8.0}
_MONTH_PEAK = {1: 450.0, 2: 520.0}


def _payload_for_date(nasa_date: str) -> dict:
    day = datetime.strptime(nasa_date, "%Y%m%d")
    temperatures, solar, wind, humidity = {}, {}, {}, {}
    for hour in range(24):
        key = f"{nasa_date}{hour:02d}"
        temperatures[key] = round(
            _MONTH_BASE[day.month] + 5.0 * np.sin(2.0 * np.pi * (hour - 8) / 24.0), 2
        )
        solar[key] = round(
            max(0.0, _MONTH_PEAK[day.month] * np.sin(np.pi * (hour - 7) / 12.0)), 1
        )
        wind[key] = 2.5
        humidity[key] = 41.0
    return {
        "properties": {
            "parameter": {
                "T2M": temperatures,
                "ALLSKY_SFC_SW_DWN": solar,
                "WS10M": wind,
                "RH2M": humidity,
            }
        }
    }


class FakeNasaTransport:
    def __call__(self, url: str, timeout_seconds: float) -> bytes:
        start = url.split("start=")[1].split("&")[0]
        return json.dumps(_payload_for_date(start)).encode()


